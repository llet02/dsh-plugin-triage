/**
 * Translations live in the harness cache dir, keyed name@version, so they
 * survive a restart and a version bump re-translates only that package.
 * Writing is best-effort: a read-only profile still renders this session's
 * translation, it just cannot persist it.
 */
const TRANSLATION_CACHE_FILE = join(homedir(), '.dsh', 'cache', 'plugin-triage-translations.json')

const CJK = /[\u4e00-\u9fff]/

function readTranslationCache() {
  try {
    const raw = JSON.parse(readFileSync(TRANSLATION_CACHE_FILE, 'utf8'))
    if (raw && typeof raw === 'object' && raw.entries && typeof raw.entries === 'object') return raw
  } catch { /* first run, or the file is gone */ }
  return { entries: {} }
}

function writeTranslationCache(cache) {
  try {
    mkdirSync(dirname(TRANSLATION_CACHE_FILE), { recursive: true })
    writeFileSync(TRANSLATION_CACHE_FILE, JSON.stringify(cache, null, 2), 'utf8')
    return true
  } catch {
    return false
  }
}

/** The cached translation for one bundle version, or null when absent. */
function cachedTranslation(cache, name, version) {
  const entry = cache.entries[name + '@' + (version ?? '')]
  return entry && typeof entry.text === 'string' && entry.text !== '' ? entry : null
}

/** A description needs translating when it carries no CJK at all. */
function needsTranslation(text) {
  return typeof text === 'string' && text.trim() !== '' && !CJK.test(text)
}

/** The host llm service, or null when this profile mounted none. */
function llmService(ctx) {
  try {
    if (typeof ctx.get !== 'function') return null
    const service = ctx.get('llm')
    return service && typeof service.stream === 'function' ? service : null
  } catch {
    return null
  }
}

function normalizeProviders(list) {
  const out = []
  for (const item of Array.isArray(list) ? list : []) {
    const name = typeof item === 'string'
      ? item
      : item && typeof item === 'object'
        ? (item.provider ?? item.route ?? item.id ?? item.key ?? item.name ?? item.label)
        : null
    if (typeof name === 'string' && name !== '' && !out.includes(name)) out.push(name)
  }
  return out
}

function normalizeModels(list) {
  const out = []
  for (const item of Array.isArray(list) ? list : []) {
    const id = typeof item === 'string'
      ? item
      : item && typeof item === 'object' ? (item.model ?? item.id ?? item.name) : null
    if (typeof id === 'string' && id !== '' && !out.includes(id)) out.push(id)
  }
  return out
}

/**
 * Pick the provider/model pair a translation call uses.
 *
 * Settings win; otherwise the first registered provider that reports a model
 * catalog is used. An empty provider list, or one that reports no models, is a
 * hard error naming both settings: guessing a provider name would only fail
 * later inside an adapter with an opaque message.
 */
async function resolveTranslationRoute(llm, config) {
  const provider = String(readField(config, 'translationProvider') ?? '').trim()
  const model = String(readField(config, 'translationModel') ?? '').trim()
  if (provider !== '' && model !== '') return { provider, model, source: 'settings' }
  const providers = normalizeProviders(await Promise.resolve(llm.listProviders?.()))
  if (providers.length === 0) {
    throw new Error('宿主 llm 服务没有已注册的 provider：请先在「设置 → 模型」启用一个 provider，或在本插件设置里填写 translationProvider / translationModel')
  }
  for (const candidate of providers) {
    let models = []
    try { models = normalizeModels(await Promise.resolve(llm.listModels?.(candidate))) } catch { models = [] }
    if (models.length > 0) {
      return { provider: candidate, model: model || models[0], source: provider === '' ? 'auto' : 'settings-provider' }
    }
  }
  if (model !== '') return { provider: providers[0], model, source: 'settings-model' }
  throw new Error('宿主 llm 服务有 ' + providers.length + ' 个 provider（' + providers.join(', ')
    + '），但都没有报告可用模型：请在本插件设置里填写 translationProvider / translationModel')
}

/** One translation attempt: the visible text of a streamed call, or ''. */
async function streamTranslation(llm, route, text) {
  const stream = llm.stream({
    provider: route.provider,
    model: route.model,
    messages: [
      {
        role: 'system',
        content: [{ type: 'text', text: '你是 DSH（DeepSeek Harness）插件市场的技术译者。只输出译文，不解释，不添加前后缀。' }],
      },
      {
        role: 'user',
        content: [{
          type: 'text',
          text: '把下面的 DSH 插件描述翻译成简体中文。保留 DSH、Harness、MCP、CLI、API 等专有名词与包名原文，'
            + '不添加说明，只输出译文（不超过 150 字）：\n\n' + text,
        }],
      },
    ],
  })
  const parts = []
  for await (const chunk of stream) {
    if (chunk && typeof chunk === 'object' && chunk.type === 'text-delta' && typeof chunk.text === 'string') {
      parts.push(chunk.text)
    }
  }
  return parts.join('').trim()
}

/**
 * Translate one description, retrying once when the call yields no visible text.
 *
 * A model may answer with reasoning only and no text-delta (observed on a long
 * catalog description); skipping the bundle on the first empty answer left a
 * permanent hole in the list while the user saw "已翻译 N 个".
 */
async function translateText(llm, route, text) {
  const first = await streamTranslation(llm, route, text)
  if (first !== '') return first
  return streamTranslation(llm, route, text)
}

