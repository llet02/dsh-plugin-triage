/**
 * The DSH *framework* version the `engines.dsh` ranges are written against.
 *
 * Plugins declare their compatibility against the version of the DSH framework,
 * which is the version of the official `@deepseek-ai/dsh-base` bundle — NOT the
 * Electron application version that a version file reports. Comparing the app
 * version against `engines.dsh` ranges like `>=0.2.2-rc.1` therefore mislabels
 * every plugin whose range bounds differ from the app number.
 *
 * `null` when no official bundle carries one: the report still works, and
 * every compat verdict then says the engine range cannot be judged.
 */
export function detectFrameworkVersion(bundles) {
  const candidates = []
  for (const bundle of bundles) {
    if (bundle.official && typeof bundle.version === 'string' && bundle.version) {
      candidates.push({ name: bundle.name, version: bundle.version })
    }
  }
  // The base bundle is authoritative; official bundles all track the same
  // framework line, so without dsh-base any official bundle is still a close
  // proxy.
  const base = bundles.find((b) => b.official && b.name === '@deepseek-ai/dsh-base')
  if (base && base.version) return { version: base.version, source: base.name }
  if (candidates.length > 0) return { version: candidates[0].version, source: candidates[0].name }
  return null
}

