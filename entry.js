/** Highest acceptable version a bundle may move to, or null when it is current. */
function pickUpdateTarget(list, installedVersion) {
  if (!list || list.status !== 'listed') return null
  let best = null
  for (const version of list.versions ?? []) {
    if (!version || typeof version.version !== 'string') continue
    if (version.incompatible) continue
    if (compareVersions(version.version, installedVersion ?? '0.0.0') <= 0) continue
    if (best === null || compareVersions(version.version, best.version) > 0) best = version
  }
  return best
}

/**
 * Who survives a conflict group: official bundles first, then the higher
 * version. A group whose top two members tie on both officiality and version is
 * NOT decided automatically — guessing would disable the wrong half, so it is
 * returned as skipped for the user to settle.
 *
 * Only enabled members can collide, and another row of the keeper's own bundle
 * is never a rival: disabling it would kill the plugin the policy just kept.
 */
function planConflictFix(report) {
  const groups = []
  for (const conflict of report.conflicts ?? []) {
    const members = (conflict.members ?? []).filter((member) => member && member.bundle && member.bundle.enabled !== false)
    if (members.length < 2) {
      groups.push({ id: conflict.id, title: conflict.title, keeper: null, disable: [], skipped: '可判定的启用成员不足 2 个' })
      continue
    }
    const ranked = [...members].sort((a, b) => {
      const official = (b.bundle.official === true ? 1 : 0) - (a.bundle.official === true ? 1 : 0)
      if (official !== 0) return official
      return compareVersions(b.bundle.version ?? '0.0.0', a.bundle.version ?? '0.0.0')
    })
    const top = ranked[0]
    const next = ranked[1]
    const tie = (next.bundle.official === true) === (top.bundle.official === true)
      && compareVersions(next.bundle.version ?? '0.0.0', top.bundle.version ?? '0.0.0') === 0
    if (tie) {
      groups.push({
        id: conflict.id, title: conflict.title, keeper: null, disable: [],
        skipped: '无法判定保留者（官方标记与版本相同），请手动选择',
      })
      continue
    }
    const disable = []
    const seen = new Set()
    for (const member of ranked.slice(1)) {
      if (member.bundle.name === top.bundle.name) continue
      if (member.bundle.name === SELF_BUNDLE) continue
      if (member.bundle.readOnlyReason) continue
      const identity = member.entryId ? 'p:' + member.entryId : 'b:' + member.bundle.name
      if (seen.has(identity)) continue
      seen.add(identity)
      disable.push(member.entryId
        ? { kind: 'plugin', name: member.entryId, entryId: member.entryId, bundleName: member.bundle.name }
        : { kind: 'bundle', name: member.bundle.name, bundleName: member.bundle.name })
    }
    groups.push({
      id: conflict.id,
      title: conflict.title,
      keeper: {
        name: top.bundle.name,
        version: top.bundle.version ?? null,
        official: top.bundle.official === true,
        entryId: top.entryId ?? null,
      },
      disable,
      skipped: disable.length === 0 ? '除了保留者没有可禁用的成员' : null,
    })
  }
  return groups
}

/** Entries and bundles the report itself marks as broken. */
function planErrorFix(report) {
  const targets = []
  const seen = new Set()
  const push = (target) => {
    if (seen.has(target.key)) return
    seen.add(target.key)
    targets.push(target)
  }
  for (const issue of report.issues ?? []) {
    const subject = issue.subject ?? {}
    // A disabled plugin cannot break a running session: re-disabling it every
    // time the button is pressed would be a no-op that reports as progress.
    if (subject.disabled === true) continue
    if (subject.kind === 'plugin' && typeof subject.entryId === 'string' && subject.entryId !== '') {
      push({
        key: 'p:' + subject.entryId, kind: 'plugin', name: subject.entryId,
        entryId: subject.entryId, reason: issue.title, type: issue.type,
      })
    } else if (subject.kind === 'bundle' && typeof subject.name === 'string' && subject.name !== '') {
      if (subject.name === SELF_BUNDLE) continue
      push({ key: 'b:' + subject.name, kind: 'bundle', name: subject.name, reason: issue.title, type: issue.type })
    }
  }
  return targets
}

/** Run a planned target list through the official manager channel. */
async function applyTargets(pm, targets) {
  const results = []
  for (const target of targets) {
    try {
      const result = target.kind === 'plugin'
        ? await pm.setPluginEnabled(String(target.entryId), false)
        : await pm.setBundleEnabled(String(target.name), false)
      results.push({
        name: target.name,
        kind: target.kind,
        ok: true,
        reason: target.reason ?? null,
        application: (result && result.application) || 'applied',
        result,
      })
    } catch (error) {
      results.push({
        name: target.name,
        kind: target.kind,
        ok: false,
        reason: target.reason ?? null,
        error: String(error && error.message ? error.message : error),
      })
    }
  }
  const failed = results.filter((entry) => !entry.ok)
  const applications = results.filter((entry) => entry.ok).map((entry) => entry.application)
  return {
    results,
    result: {
      application: failed.length > 0
        ? 'failed'
        : applications.includes('restart-required') ? 'restart-required' : 'applied',
      disabled: results.length - failed.length,
      failed: failed.length,
      warnings: failed.map((entry) => entry.name + ': ' + entry.error),
    },
  }
}

/** A slot id occupied by at least one entry; up to 200 distinct ids per scope. */
function takenSlotKeys(scope) {
  const scopeNode = scope.subTree
  const taken = new Set()
  let walked = 0
  const queue = [scopeNode]
  while (queue.length > 0 && walked < 200) {
    const node = queue.pop()
    if (!node) continue
    if (node.nodeType) {
      const keys = node.keySet ? node.keySet() : []
      for (const key of keys) {
        if (typeof key === 'string' && key.length > 0) {
          taken.add(key)
          if (taken.size >= 200) return taken
        }
      }
    }
    for (const child of node.children || []) queue.push(child)
  }
  return taken
}

/** Sort bundles by name, official core layers first (they are read-only anyway). */
function sortBundles(bundles) {
  return [...bundles].sort((a, b) => {
    if (!!a.official !== !!b.official) return a.official ? -1 : 1
    return String(a.name).localeCompare(String(b.name))
  })
}

/**
 * Full diagnostic snapshot, computed inside the same process the manager runs,
 * so it always agrees with the Plugins page.
 */
async function buildReport(ctx, config) {
  const runtimeVersion = detectRuntimeVersion()
  // Wrap each call in Promise.resolve: `listVersionExemptions` is declared
  // without `async` (its spy resolves synchronously), so calling `.catch` on
  // the raw return value threw before any report could be read.
  const exemptionsData = await Promise.resolve(ctx.pluginManager.listVersionExemptions()).catch((error) => { ctx.logger?.warn?.('plugin-triage: listVersionExemptions failed', error); return { exemptions: {}, warnings: [] } })
  const [plugins, bundles] = await Promise.all([
    ctx.pluginManager.listPlugins().catch((error) => { ctx.logger?.warn?.('plugin-triage: listPlugins failed', error); return [] }),
    ctx.pluginManager.listBundles().catch((error) => { ctx.logger?.warn?.('plugin-triage: listBundles failed', error); return [] }),
  ])

  const now = Date.now()

  const conflicts = []
  const sharedClientDependencies = []
  const issues = []
  let id = 0
  let platformOverlapCount = 0
  const nextId = () => `c${++id}`

  /** Find a bundle by name in the just-fetched bundle set. */
  const bundleByName = (name) => bundles.find((b) => b.name === name)

  /**
   * Runtime entry state, so conflict detection only counts entries that are
   * actually running. A disabled row cannot collide with anything: reporting
   * it as a conflict turns a clean installation into a wall of red.
   */
  const pluginByEntryId = new Map()
  for (const plugin of plugins) {
    if (plugin && typeof plugin.entryId === 'string') pluginByEntryId.set(plugin.entryId, plugin)
  }
  const entryEnabled = (entryId) => {
    const plugin = pluginByEntryId.get(entryId)
    return plugin === undefined ? true : plugin.enabled !== false
  }
  /** Enabled installed bundles are the only ones whose rows can collide. */
  const liveBundles = bundles.filter((b) => b.installed && b.enabled !== false)

  /**
   * Attach concrete patch-file evidence to a bundle: which entries its
   * `cordis.patch.yml` declares, and the exact patch file path. This is the
   * "who declared what, where" evidence the conflict report needs.
   */
  const patchCache = new Map()
  const patchFor = (name) => {
    if (patchCache.has(name)) return patchCache.get(name)
    let patch = null
    try {
      const manifest = readManifest(name)
      patch = readPatchDetail(name, manifest)
    } catch (error) {
      patch = null
    }
    patchCache.set(name, patch)
    return patch
  }

  /**
   * A group only counts as a conflict when at least one member is NOT a DSH
   * framework bundle. Framework bundles (`@deepseek-ai/dsh-*`) legitimately
   * overlap each other — base, sdk-minimal, sdk-app and web-app declare the
   * same entry ids across layers as a designed layering mechanism (web-app
   * overlays base). Their overlap is the framework's own extension pattern,
   * not a problem. The plugin inventory reports those overlap groups as
   * informational in `stats.platformOverlapGroups` but not as conflicts.
   */
  const isFrameworkBundle = (name) => typeof name === 'string' && name.startsWith('@deepseek-ai/')

  // --- 1. duplicate entry ids across enabled bundles (重复挂载同一个入口) ---
  // Disabled bundles and disabled entries cannot collide at runtime, so they are
  // not conflicts. Their packages remain visible in the compatibility table and
  // in search, where they can be re-enabled deliberately.
  {
    const byEntryId = new Map()
    for (const bundle of liveBundles) {
      for (const row of bundle.rows ?? []) {
        if (!row.entryId || !entryEnabled(row.entryId)) continue
        if (!byEntryId.has(row.entryId)) byEntryId.set(row.entryId, [])
        byEntryId.get(row.entryId).push({ bundle: bundle.name, rowId: row.rowId, moduleName: row.moduleName })
      }
    }
    for (const [entryId, members] of byEntryId) {
      const sources = new Set(members.map((m) => m.bundle))
      if (sources.size < 2) continue
      // Skip pure framework overlaps: base/sdk/web-app chaining over each
      // other's rows is the framework's designed layering, not a conflict.
      if (members.every((m) => isFrameworkBundle(m.bundle))) { platformOverlapCount++; continue }
      conflicts.push({
        id: nextId(),
        type: 'duplicate-entry',
        severity: 'high',
        title: `入口 ${entryId} 被多个启用插件包同时挂载`,
        detail: `同一加载器入口由 ${sources.size} 个已启用插件包重复注册（已禁用的同类包不参与）：`,
        advice: '保留需要的那一个，其余启用的包请「禁用」或「删除」，否则启动时可能报重复注册或加载失败。',
        enabledMembers: sources.size,
        members: members.map((m) => ({
          kind: 'row', sourceBundle: m.bundle, rowId: m.rowId, entryId,
          moduleName: m.moduleName,
          bundle: bundles.find((b) => b.name === m.bundle),
          patch: patchFor(m.bundle),
        })),
      })
    }
  }

  // --- 2. one module mounted by several enabled bundles (重复装载模块) ---
  {
    const byModule = new Map()
    for (const bundle of liveBundles) {
      for (const row of bundle.rows ?? []) {
        if (!row.moduleName || !entryEnabled(row.entryId)) continue
        if (!byModule.has(row.moduleName)) byModule.set(row.moduleName, [])
        byModule.get(row.moduleName).push({ bundle: bundle.name, rowId: row.rowId, entryId: row.entryId })
      }
    }
    for (const [moduleName, members] of byModule) {
      const sources = new Set(members.map((m) => m.bundle))
      if (sources.size < 2) continue
      if (members.every((m) => isFrameworkBundle(m.bundle))) { platformOverlapCount++; continue }
      conflicts.push({
        id: nextId(),
        type: 'duplicate-module',
        severity: 'high',
        title: `模块 ${moduleName} 被多个启用插件包重复装载`,
        detail: `同一 npm 模块作为不同入口被 ${sources.size} 个已启用包引用，可能造成重复注册或相互覆盖。已禁用的包不参与。`,
        advice: '只保留声明该模块的那一个包；如果它只是被间接依赖，优先删除多余包。',
        enabledMembers: sources.size,
        members: members.map((m) => ({ kind: 'row', ...m, bundle: bundles.find((b) => b.name === m.bundle), patch: patchFor(m.bundle) })),
      })
    }
  }

  // --- 3. shared client module dependencies (客户端模块依赖共享，正常现象) ---
  // `dsh.client.inject` is the list of client-side modules a bundle DEPENDS ON,
  // not a list of UI mount points it registers into. Two plugins both naming
  // `@deepseek-ai/dsh-client-ui-settings` merely reuse the same module; DSH
  // resolves one instance. Treating that as a conflict produced a wall of red
  // false positives, so it is reported separately as informational data.
  {
    const byInject = new Map()
    for (const bundle of bundles.filter((b) => b.installed)) {
      const manifest = readManifest(bundle.name)
      const injectList = Array.isArray(manifest?.dsh?.client?.inject) ? manifest.dsh.client.inject : []
      for (const slot of injectList) {
        if (!byInject.has(slot)) byInject.set(slot, [])
        byInject.get(slot).push({ bundle: bundle.name, manifest })
      }
    }
    for (const [slot, members] of byInject) {
      const sources = new Set(members.map((m) => m.bundle))
      if (sources.size < 2) continue
      const enabledMembers = members.filter((m) => {
        const bundle = bundles.find((b) => b.name === m.bundle)
        return bundle && bundle.enabled !== false
      })
      if (enabledMembers.length < 2) continue
      if (enabledMembers.every((m) => isFrameworkBundle(m.bundle))) { platformOverlapCount++; continue }
      // Only surface shared dependencies that involve at least one non-framework
      // plugin: framework-to-framework reuse is invisible plumbing.
      if (!enabledMembers.some((m) => !isFrameworkBundle(m.bundle))) continue
      sharedClientDependencies.push({
        id: `s${sharedClientDependencies.length + 1}`,
        slot,
        title: `客户端模块 ${slot} 被 ${enabledMembers.length} 个启用插件共享`,
        detail: '这是客户端依赖共享，不是挂载点冲突：DSH 会复用同一个模块实例。只有两个插件注册同一个 UI 槽位 id 时才可能互相覆盖。',
        enabledMembers: enabledMembers.length,
        members: members.map((m) => {
          const bundle = bundles.find((b) => b.name === m.bundle)
          return {
            kind: 'bundle',
            sourceBundle: m.bundle,
            bundle,
            enabled: !!bundle && bundle.enabled !== false,
            thirdParty: !!bundle && bundle.official !== true,
            patch: patchFor(m.bundle),
          }
        }),
      })
    }
    sharedClientDependencies.sort((a, b) => String(a.slot).localeCompare(String(b.slot)))
  }

  // --- 4. version compatibility of installed bundles ---
  const exemptions = exemptionsData.exemptions ?? {}
  const exemptionWarnings = exemptionsData.warnings ?? []

  // The DSH FRAMEWORK version — what `engines.dsh` ranges are written against.
  // Not the Electron application version (44.7.0): comparing plugin ranges to
  // that mislabels every plugin whose range is in the 0.2.x framework line.
  const framework = detectFrameworkVersion(bundles)
  const engineVersion = framework ? framework.version : null
  const engineVersionSource = framework ? framework.source : null

  const compatByBundle = new Map()
  for (const bundle of bundles) {
    const manifest = readManifest(bundle.name)
    if (!manifest) continue
    const engineRange = manifest.dsh?.engines?.dsh ?? manifest.engines?.dsh ?? null
    const nodeRange = manifest.engines?.node ?? null
    let status = 'ok'
    let reason = ''
    let failure = null
    if (engineRange !== null && engineRange !== undefined && String(engineRange).trim() !== '') {
      if (engineVersion === null) {
        // Nothing to compare against: neither the framework nor the app version
        // can be established. Do NOT guess — report as unknown, with the range
        // spelled out so a human can judge it (they installed and run the plugin
        // already; this verdict is advisory, not a gate).
        status = 'unknown'
        reason = `声明引擎 ${engineRange}；本机未读到官方框架版本（${engineVersionSource || '未识别'}），请人工对照该范围与官方包版本决定是否保留`
      } else {
        const ok = satisfies(engineVersion, engineRange)
        if (!ok) {
          const key = `${bundle.name}@${bundle.version}`
          const exempted = Object.prototype.hasOwnProperty.call(exemptions, key)
          if (exempted) {
            status = 'exempted'
            reason = `声明引擎 ${engineRange}，不含当前框架版本 ${engineVersion}，但已设置豁免`
          } else {
            status = 'incompatible'
            reason = `声明引擎 ${engineRange}，当前 DSH 框架版本 ${engineVersion}`
            failure = { key, range: String(engineRange), engineVersion }
          }
        } else {
          // compatible
        }
      }
    } else if (bundle.official) {
      // official bundles follow the DSH version by construction
      status = 'ok'
    } else {
      status = 'unknown'
      reason = '未声明 engines.dsh，无法静态判定；安装/更新时由插件管理器强制校验'
    }
    if (manifest.dsh?.client?.platform && manifest.dsh.client.platform !== 'web') {
      // other platforms are irrelevant to a web GUI; do not flag them
    }
    compatByBundle.set(bundle.name, { status, reason, engineRange, nodeRange, failure, manifest })
    if (status === 'incompatible' && bundle.enabled) {
      issues.push({
        id: nextId(),
        type: 'incompatible',
        severity: 'high',
        title: `${bundle.name} 与当前 DSH 版本不兼容`,
        detail: reason + '。插件管理器会在启动或更新时拒绝加载，也可能表现为功能缺失。',
        advice: '升级该插件到兼容版本，或停用/删除它；确认了解风险后可在「版本兼容」区设置豁免放行。',
        subject: { kind: 'bundle', name: bundle.name, version: bundle.version },
      })
    }
  }

  // --- 5. failed / pending fibers and bundle management errors ---
  for (const plugin of plugins) {
    if (plugin.fiberPhase === 'failed') {
      issues.push({
        id: nextId(),
        type: 'failed',
        severity: 'high',
        title: `插件 ${plugin.entryId} 加载失败`,
        detail: plugin.diagnostic ? String(plugin.diagnostic) : '未提供诊断信息。',
        advice: '查看插件详情页的报错；通常需要禁用该插件或删除其所属包。',
        subject: { kind: 'plugin', entryId: plugin.entryId, moduleName: plugin.moduleName, disabled: plugin.enabled === false },
      })
    } else if (plugin.fiberPhase === 'pending') {
      issues.push({
        id: nextId(),
        type: 'pending',
        severity: 'medium',
        title: `插件 ${plugin.entryId} 仍在等待加载`,
        detail: '可能是因为依赖的服务未就绪，或配置行有悬空依赖。',
        advice: '等待数秒后重新打开此标签页；持续 pending 建议禁用再启用。',
        subject: { kind: 'plugin', entryId: plugin.entryId, moduleName: plugin.moduleName, disabled: plugin.enabled === false },
      })
    }
  }
  for (const bundle of bundles) {
    if (!bundle.error) continue
    // Optional built-in bundles that this platform cannot provide are not
    // installation problems: `dsh-cua-bundle` is reported as
    // `unsupported-platform` on Windows while never being installed. Treating
    // that as a red issue makes a healthy profile look broken.
    if (!bundle.installed && bundle.official) continue
    {
      issues.push({
        id: nextId(),
        type: 'bundle-error',
        severity: bundle.error.code === 'incompatible-version' ? 'high' : 'medium',
        title: `插件包 ${bundle.name} 存在管理错误（${bundle.error.code}）`,
        detail: bundle.error.diagnostic ?? '见插件管理器日志。',
        advice: '尝试更新该包；错误持续时删除后重新安装。',
        subject: { kind: 'bundle', name: bundle.name, version: bundle.version, disabled: bundle.enabled === false },
        patch: patchFor(bundle.name),
      })
    }
  }

  // One scan per installed bundle, reused by the bundle rows and the summary.
  const capabilityByBundle = new Map()
  for (const bundle of bundles) {
    if (bundle.installed) capabilityByBundle.set(bundle.name, scanCapabilities(bundle.name))
  }
  const capabilityCounts = {}
  for (const caps of capabilityByBundle.values()) {
    for (const tag of caps.tags) capabilityCounts[tag.key] = (capabilityCounts[tag.key] ?? 0) + 1
  }
  const translationCache = readTranslationCache()
  // Every bundle in the inventory may carry a translatable description: the
  // installed third-party ones AND the official catalog entries that are not
  // installed yet. Both lists are translated, so the count covers both.
  const translationOf = (name, version) => cachedTranslation(translationCache, name, version)
  const untranslatedCount = bundles.filter(
    (bundle) => needsTranslation(bundle.description) && translationOf(bundle.name, bundle.version) === null,
  ).length

  const stats = {
    runtimeVersion,
    engineVersion,
    engineVersionSource,
    runtimeVersionNote: runtimeVersion === null ? '无法读取当前 DSH 版本：请设置 DSH_VERSION 环境变量后重启' : '',
    plugins: plugins.length,
    bundles: bundles.length,
    installedBundles: bundles.filter((b) => b.installed).length,
    thirdPartyBundles: bundles.filter((b) => b.installed && !b.official).length,
    thirdPartyEnabled: bundles.filter((b) => b.installed && !b.official && b.enabled !== false).length,
    conflictGroups: conflicts.length,
    platformOverlapGroups: platformOverlapCount,
    conflictMembers: conflicts.reduce((sum, c) => sum + c.members.length, 0),
    sharedClientDependencies: sharedClientDependencies.length,
    issues: issues.length,
    incompatible: [...issues].filter((i) => i.type === 'incompatible').length,
    failed: [...issues].filter((i) => i.type === 'failed').length,
    exempted: [...compatByBundle.values()].filter((c) => c.status === 'exempted').length,
    capabilityCounts,
    untranslated: untranslatedCount,
  }

  return {
    ok: true,
    generatedAt: now,
    runtimeVersion,
    engineVersion,
    engineVersionSource,
    config: {
      enabled: config.enabled !== false,
      autoRefreshSeconds: typeof config.autoRefreshSeconds === 'number' ? config.autoRefreshSeconds : 30,
      showConsequenceHints: config.showConsequenceHints !== false,
    },
    stats,
    plugins: plugins.map((p) => ({ ...p })),
    bundles: sortBundles(bundles).map((b) => ({
      ...b,
      thirdParty: b.installed && !b.official,
      patch: b.installed ? patchFor(b.name) : null,
      capabilities: capabilityByBundle.get(b.name) ?? null,
      descriptionZh: translationOf(b.name, b.version),
      compat: compatByBundle.get(b.name) ?? {
        status: b.installed ? 'unknown' : 'n/a',
        reason: b.installed ? '未读到包清单（manifest）' : '未安装，安装时由管理器校验',
        engineRange: null, nodeRange: null, failure: null,
      },
    })),
    conflicts,
    sharedClientDependencies,
    issues,
    exemptions: { exemptions, warnings: exemptionWarnings },
    official: bundles
      .filter((b) => !b.installed && (b.official || b.availability === 'installation'))
      .map((b) => ({
        name: b.name,
        version: b.version,
        official: b.official,
        description: b.description,
        descriptionZh: translationOf(b.name, b.version),
        installTarget: b.installTarget ?? null,
        enabled: b.enabled,
      })),
  }
}

