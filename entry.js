/**
 * Keyword families that mark a contribution surface. A hit is evidence shown to
 * the user (file + line), not a verdict: each tag carries the lines that matched.
 */
const CAPABILITY_RULES = [
  { key: 'tool', label: '工具', re: /\bdefineTool\b|\bctx\.tool\b|\bctx\.tools\b|\bregisterTool\b|\btoolRegistry\b/ },
  { key: 'model', label: '模型', re: /\bctx\.llm\b|\bregisterAdapter\b|\blistProviders\s*\(/ },
  { key: 'ui', label: 'UI视图', re: /\bslots\.(?:register|inject)\b|\bplugins\.tab\b/ },
  { key: 'route', label: 'Web接口', re: /\bwebServer\.register\b/ },
  { key: 'command', label: '命令', re: /\bctx\.command\s*\(|\bregisterCommand\b/ },
  { key: 'skill', label: '技能', re: /\bctx\.skills?\b|\bregisterSkill\b/ },
  { key: 'agent', label: '子代理', re: /\bsubagent\b|\bspawnAgent\b/ },
  { key: 'mcp', label: 'MCP', re: /\bmcpServer\b|\bctx\.mcp\b/ },
  { key: 'schedule', label: '后台任务', re: /\bsetInterval\s*\(|\bctx\.timer\b|\bcron\b/i },
  { key: 'session', label: '会话投影', re: /\bsessionProjections\b/ },
  { key: 'storage', label: '本地存储', re: /\bctx\.storage\b|\bwriteFileSync\b/ },
  { key: 'shell', label: '执行命令', re: /\bnode:child_process\b|\bexecFile\b/ },
  { key: 'catalog', label: '插件目录', re: /\bpluginMarket\b|\bplugin_market\b/ },
]

const CAPABILITY_LABELS = Object.fromEntries(CAPABILITY_RULES.map((rule) => [rule.key, rule.label]))

/** A patch row id names the surface that row mounts. */
const PATCH_PREFIX_TAGS = [
  { prefix: 'tool', key: 'tool' },
  { prefix: 'client', key: 'ui' },
  { prefix: 'ui', key: 'ui' },
  { prefix: 'skill', key: 'skill' },
  { prefix: 'mcp', key: 'mcp' },
  { prefix: 'subagent', key: 'agent' },
  { prefix: 'market', key: 'catalog' },
]

/** name@version -> scan result; a version bump invalidates it naturally. */
const capabilityCache = new Map()

/** The module a bundle's entry export points at. */
function resolveEntryPath(manifest) {
  let entryExport = manifest.dsh?.bundle?.entry
  if (!entryExport) {
    const exp = manifest.exports?.['.']
    if (typeof exp === 'string') entryExport = exp
    else if (exp && typeof exp === 'object') entryExport = exp.default ?? exp['.'] ?? manifest.main
    if (!entryExport) entryExport = manifest.main ?? 'entry.js'
  }
  return join(manifest.dir, entryExport)
}

/** Files worth scanning: the declared entry plus up to five lib/*.js. */
function scanFilesFor(manifest) {
  const files = []
  const add = (full) => {
    if (files.length < 6 && existsSync(full) && !files.includes(full)) files.push(full)
  }
  add(resolveEntryPath(manifest))
  try {
    const libDir = join(manifest.dir, 'lib')
    if (existsSync(libDir)) {
      for (const name of readdirSync(libDir).sort()) {
        if (name.endsWith('.js')) add(join(libDir, name))
      }
    }
  } catch { /* unreadable lib dir: the entry alone is enough */ }
  return files
}

/**
 * Classify one installed bundle's contribution surface.
 *
 * Three sources, cheapest first: the manifest's own declarations, the rows its
 * cordis.patch.yml inserts, then a bounded keyword scan of its entry and lib
 * files. Every tag keeps up to three {file, line} witnesses, so a user can jump
 * to the line instead of trusting a label.
 */
function scanCapabilities(pkgName) {
  const manifest = readManifest(pkgName)
  if (!manifest) return { tags: [], summary: '未读到包清单（manifest）' }
  const cacheKey = pkgName + '@' + (manifest.version ?? '')
  const cached = capabilityCache.get(cacheKey)
  if (cached !== undefined) return cached

  const found = new Map()
  const add = (key, evidence) => {
    if (CAPABILITY_LABELS[key] === undefined) return
    if (!found.has(key)) found.set(key, [])
    const list = found.get(key)
    if (evidence && list.length < 3) list.push(evidence)
  }

  if (manifest.dsh?.client) add('ui', { file: 'package.json', line: 0 })

  const patch = readPatchDetail(pkgName, manifest)
  for (const decl of (patch?.declarations ?? [])) {
    for (const rule of PATCH_PREFIX_TAGS) {
      if (decl.id === rule.prefix || decl.id.startsWith(rule.prefix + '-')) {
        add(rule.key, { file: 'cordis.patch.yml', line: decl.line })
      }
    }
  }

  for (const file of scanFilesFor(manifest)) {
    let text
    try { text = readFileSync(file, 'utf8') } catch { continue }
    if (text.length > 512 * 1024) text = text.slice(0, 512 * 1024)
    const rel = file.slice(manifest.dir.length + 1).replace(/\\/g, '/')
    const lines = text.split(/\r?\n/)
    for (let i = 0; i < lines.length; i += 1) {
      for (const rule of CAPABILITY_RULES) {
        if ((found.get(rule.key) ?? []).length >= 3) continue
        if (rule.re.test(lines[i])) add(rule.key, { file: rel, line: i + 1 })
      }
    }
  }

  const order = CAPABILITY_RULES.map((rule) => rule.key)
  const tags = [...found.keys()]
    .map((key) => ({ key, label: CAPABILITY_LABELS[key], evidence: found.get(key) }))
    .sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key))
  const result = { tags, summary: tags.length === 0 ? '未识别到贡献面' : tags.map((tag) => tag.label).join(' / ') }
  capabilityCache.set(cacheKey, result)
  return result
}

