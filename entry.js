/** Node's homedir, wrapped so a non-Node host cannot break the import. */
function homeDir() {
  try {
    // `homedir` exists since Node 20 and never throws here.
    return homedir()
  } catch {
    return null
  }
}

/**
 * Candidate profile roots.
 *
 * The manifest scanner needs node_modules directories for two kinds of install:
 *   * a profile-root install — profile/node_modules/<pkg>;
 *   * a `file:`/`link:` install whose real home is the source dir, which may
 *     carry its own node_modules.
 *
 * The entry file itself runs from wherever its patch resolved, which is
 * the source dir for a local install and the profile's node_modules for a
 * published install. Both candidates are therefore built from the entry
 * path, plus the conventional profile directories.
 * @returns distinct absolute directory paths, most specific first.
 */
function profileRootCandidates() {
  const roots = []
  const seen = new Set()
  const add = (dir) => {
    if (!dir) return
    const normalised = dir.replace(/\/+$/, '')
    if (!normalised || seen.has(normalised)) return
    seen.add(normalised)
    roots.push(normalised)
  }
  // Environment override, never set by default.
  add(process.env?.DSH_PROFILE_ROOT)
  // The conventional per-OS profile locations.
  const home = homeDir()
  if (home !== null) {
    for (const name of ['desktop', 'web']) {
      add(join(home, '.dsh', 'profiles', name))
    }
  }
  // Walk up from this module; for each level whose node_modules survives, the
  // level itself is a profile root (the dir containing node_modules).
  const here = fileURLToPath(import.meta.url)
  let dir = dirname(here)
  for (let i = 0; i < 8; i++) {
    if (existsSync(join(dir, 'node_modules'))) add(dir)
    const parent = dirname(dir)
    if (parent === dir) break
    dir = parent
  }
  // The directory itself, for direct `<root>/<name>` resolution of this entry.
  add(fileURLToPath(dirname(import.meta.url)))
  return roots
}

let profileRootsCache = null

/** @returns const-marked candidate root list */
function roots() {
  if (profileRootsCache === null) profileRootsCache = profileRootCandidates()
  return profileRootsCache
}

/** Read one installed bundle's manifest; null when it is not physically present. */
function readManifest(pkgName, rootsList) {
  const list = rootsList ?? roots()
  for (const root of list) {
    // Registry installs sit under <root>/node_modules/<scope?>/<name>.
    const underPackages = join(root, 'node_modules', pkgName)
    const underPackagesFile = underPackages + '/package.json'
    if (existsSync(underPackagesFile)) {
      try {
        const raw = JSON.parse(readFileSync(underPackagesFile, 'utf8'))
        return {
          name: raw.name ?? pkgName,
          version: raw.version,
          description: raw.description,
          keywords: Array.isArray(raw.keywords) ? raw.keywords : [],
          engines: raw.engines && typeof raw.engines === 'object' ? raw.engines : {},
          dsh: raw.dsh && typeof raw.dsh === 'object' ? raw.dsh : {},
          license: raw.license,
          homepage: raw.homepage,
          main: raw.main,
          exports: raw.exports,
          source: `${root}\\node_modules\\${pkgName}`,
          dir: underPackages,
        }
      } catch (error) {
        // Keep looking — another candidate root may hold a different copy.
      }
    }
    // `file:` installs may be linked at <root>/<name>.
    const fallback = join(root, pkgName)
    if (existsSync(fallback + '/package.json')) {
      try {
        const raw = JSON.parse(readFileSync(fallback + '/package.json', 'utf8'))
        return {
          name: raw.name ?? pkgName,
          version: raw.version,
          description: raw.description,
          keywords: Array.isArray(raw.keywords) ? raw.keywords : [],
          engines: raw.engines && typeof raw.engines === 'object' ? raw.engines : {},
          dsh: raw.dsh && typeof raw.dsh === 'object' ? raw.dsh : {},
          license: raw.license,
          homepage: raw.homepage,
          main: raw.main,
          exports: raw.exports,
          source: fallback,
          dir: fallback,
        }
      } catch (error) {
        // fall through to the next candidate
      }
    }
  }
  return null
}

/**
 * Read a bundle's `cordis.patch.yml` and extract the declaration lines that
 * contribute entries. This is the concrete "who declared what" evidence the
 * conflict report needs: for each row id, the exact patch line (with its line
 * number in the file) that names it.
 */
function readPatchDetail(pkgName, manifest) {
  try {
    if (!manifest || !manifest.dir) return null
    const patchRel = manifest.dsh?.bundle?.patch ?? 'cordis.patch.yml'
    const patchPath = join(manifest.dir, patchRel)
    if (!existsSync(patchPath)) return null
    const text = readFileSync(patchPath, 'utf8')
    const lines = text.split(/\r?\n/)
    const declarations = []
    let inInsert = false
    for (let i = 0; i < lines.length; i += 1) {
      const line = lines[i]
      const lineNo = i + 1
      if (/^-\s*insert:/m.test(line) || /^\s*- insert:/m.test(line)) inInsert = true
      const idMatch = /^\s*[-*]?\s*id:\s*(.+)$/.exec(line)
      if (idMatch) {
        const id = idMatch[1].replace(/['"]/g, '').trim()
        declarations.push({ id, line: lineNo })
      }
    }
    return {
      patchPath,
      patchLines: lines.length,
      declarations: declarations.slice(0, 40),
    }
  } catch (error) {
    return null
  }
}

/**
 * Diagnostically import one bundle's entry module in a child process, so the
 * actual runtime error (file + line + stack) can be shown to the user.
 *
 * A plugin's entry module normally expects a Host plugin context; importing it
 * bare with no context will throw for most plugins (they call `ctx.effect(...)`
 * etc. at module top level). That is expected: the value is the error text,
 * which tells the user exactly which file and line the plugin breaks at.
 *
 * @returns `{ ok, error, stack, exitCode }` — `ok` is always true (the call
 *   succeeded); inspect `error` to see whether the import itself failed.
 */
async function diagnoseBundle(ctx, pkgName) {
  const manifest = readManifest(pkgName)
  if (!manifest) {
    return { ok: true, error: '无法读取包清单（manifest）', stack: null, exitCode: -1 }
  }
  // Resolve the entry module path: dsh.bundle.entry > exports['.'].default > main > entry.js
  let entryExport = manifest.dsh?.bundle?.entry
  if (!entryExport) {
    const exp = manifest.exports?.['.']
    if (typeof exp === 'string') entryExport = exp
    else if (exp && typeof exp === 'object') entryExport = exp.default ?? exp['.'] ?? manifest.main
    if (!entryExport) entryExport = manifest.main ?? 'entry.js'
  }
  const entryPath = join(manifest.dir, entryExport)
  if (!existsSync(entryPath)) {
    return { ok: true, error: `入口文件不存在：${entryPath}`, stack: null, exitCode: -1 }
  }
  try {
    const { execFile } = await import('node:child_process')
    const entryUrl = 'file://' + entryPath.replace(/\\/g, '/')
    const script = [
      `const entryUrl = ${JSON.stringify(entryUrl)}`,
      `try {`,
      `  await import(entryUrl)`,
      `  console.log('DIAG_OK')`,
      `} catch (e) {`,
      `  console.log('DIAG_FAIL ' + JSON.stringify({ message: e && e.message, stack: e && e.stack }))`,
      `}`,
    ].join('\n')
    const child = await new Promise((resolve, reject) => {
      execFile(process.execPath, ['-e', script, entryUrl], {
        timeout: 10000,
        cwd: manifest.dir,
        encoding: 'utf8',
      }, (error, stdout, stderr) => {
        if (error && typeof error === 'object' && error.killed) {
          resolve({ killed: true, stdout: '', stderr: '' })
        } else if (error && error.signal) {
          resolve({ killed: true, stdout: '', stderr: stderr || '' })
        } else {
          resolve({ killed: false, stdout: stdout || '', stderr: stderr || '' })
        }
      })
    })
    if (child.killed) {
      return { ok: true, error: '子进程超时（10 秒），插件入口在加载阶段卡住', stack: child.stderr?.slice(0, 2000), exitCode: -1 }
    }
    const lines = child.stdout.split(/\r?\n/).filter(Boolean)
    if (lines.some((l) => l.startsWith('DIAG_FAIL'))) {
      for (const l of lines) {
        if (l.startsWith('DIAG_FAIL ')) {
          const raw = l.slice('DIAG_FAIL '.length)
          const parsed = JSON.parse(raw)
          return { ok: true, error: parsed.message || '导入失败', stack: parsed.stack || null, exitCode: 1 }
        }
      }
    }
    // SyntaxErrors during evaluation can leave partial output in stderr.
    if (child.stderr && child.stderr.trim() !== '') {
      return { ok: true, error: child.stderr.slice(0, 500), stack: child.stderr.slice(0, 2000), exitCode: 1 }
    }
    return { ok: true, error: null, stack: null, exitCode: 0 }
  } catch (error) {
    return { ok: true, error: String(error && error.message ? error.message : error), stack: String(error && error.stack), exitCode: -1 }
  }
}

