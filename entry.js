/**
 * The engine version the compatibility check compares `engines.dsh` against.
 *
 * Sources, in order of trust:
 *   1. `DSH_VERSION` env var, when the launcher sets it;
 *   2. the sibling `version` file of the Electron resources directory
 *      (the desktop build writes the exact build version there);
 *   3. the version of the newest official bundle, which follows the DSH version.
 *
 * `null` when nothing is readable: the report then flags compatibility checks as
 * `unknown` instead of guessing.
 */
export function detectRuntimeVersion() {
  try {
    const env = process.env.DSH_VERSION
    if (typeof env === 'string' && /^\d/.test(env.trim())) return env.trim()
  } catch { /* env is not always readable */ }
  try {
    if (process.resourcesPath) {
      const file = join(process.resourcesPath, '..', 'version')
      const raw = readFileSync(file, 'utf8').trim()
      if (/^\d/.test(raw)) return raw
    }
  } catch { /* non-desktop builds have no version file */ }
  return null
}

