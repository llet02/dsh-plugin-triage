function sendJson(res, status, payload) {
  const body = JSON.stringify(payload)
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
  })
  res.end(body)
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = []
    req.on('data', (chunk) => {
      chunks.push(chunk)
      if (chunks.reduce((n, c) => n + c.length, 0) > 1_000_000) {
        reject(new Error('payload too large'))
        req.destroy()
      }
    })
    req.on('end', () => {
      try {
        resolve(chunks.length === 0 ? {} : JSON.parse(Buffer.concat(chunks).toString('utf8')))
      } catch (error) {
        reject(error)
      }
    })
    req.on('error', reject)
  })
}

function isLoopback(req) {
  const address = req.socket?.remoteAddress
  if (!address) return true
  return LOOPBACK.has(address)
}

/** Map the UI's verb to one pluginManager call. Each returns { result } or throws. */
async function runAction(ctx, config, action, body) {
  const pm = ctx.pluginManager
  switch (action) {
    case 'enable-plugin': {
      const result = await pm.setPluginEnabled(String(body.entryId), true)
      return { result }
    }
    case 'disable-plugin': {
      const result = await pm.setPluginEnabled(String(body.entryId), false)
      return { result }
    }
    case 'enable-bundle': {
      const result = await pm.setBundleEnabled(String(body.name), true)
      return { result }
    }
    case 'disable-bundle': {
      const result = await pm.setBundleEnabled(String(body.name), false)
      return { result }
    }
    case 'disable-bundles': {
      const names = [...new Set(
        (Array.isArray(body.names) ? body.names : [])
          .map((name) => String(name ?? '').trim())
          .filter((name) => name !== ''),
      )]
      if (names.length === 0) throw new Error('names is required')
      if (names.length > 100) throw new Error('一次最多禁用 100 个插件包')
      const results = []
      for (const name of names) {
        try {
          const result = await pm.setBundleEnabled(name, false)
          results.push({ name, ok: true, result })
        } catch (error) {
          results.push({ name, ok: false, error: String(error && error.message ? error.message : error) })
        }
      }
      const failed = results.filter((entry) => !entry.ok)
      const applications = results
        .filter((entry) => entry.ok)
        .map((entry) => (entry.result && entry.result.application) || 'applied')
      const application = failed.length > 0
        ? 'failed'
        : applications.includes('restart-required') ? 'restart-required' : 'applied'
      return {
        results,
        result: {
          application,
          warnings: failed.map((entry) => `${entry.name}: ${entry.error}`),
        },
      }
    }
    case 'remove-bundle': {
      const result = await pm.removeBundle(String(body.name))
      return { result }
    }
    case 'install': {
      const result = await pm.installBundle(String(body.spec), {
        enabled: body.enabled !== false,
        approvedBuilds: Array.isArray(body.approvedBuilds) ? body.approvedBuilds : undefined,
      })
      return { result }
    }
    case 'versions': {
      const result = await pm.listVersions(String(body.name))
      return { result }
    }
    case 'update': {
      const result = await pm.updateBundle(String(body.name), String(body.version))
      return { result }
    }
    case 'exemption-set': {
      const result = await pm.setVersionExemption(
        String(body.packageVersion), String(body.runtimeVersion), true,
        body.acceptRisk === true,
      )
      return { result }
    }
    case 'exemption-remove': {
      const result = await pm.setVersionExemption(
        String(body.packageVersion), String(body.runtimeVersion), false,
      )
      return { result }
    }
    case 'diagnose': {
      const names = Array.isArray(body.names) ? body.names : []
      const results = []
      for (const name of names) {
        // Cap the batch so one slow plugin cannot hang the request.
        if (results.length >= 20) break
        results.push({ name, result: await diagnoseBundle(ctx, String(name)) })
      }
      return { diagnosis: results }
    }
    case 'update-all': {
      const all = await pm.listBundles()
      const pool = all.filter((bundle) => bundle.installed && bundle.official !== true && bundle.enabled !== false)
      const candidates = pool.slice(0, 20)
      const results = []
      for (const bundle of candidates) {
        let list
        try {
          list = await pm.listVersions(bundle.name)
        } catch (error) {
          results.push({ name: bundle.name, ok: false, from: bundle.version ?? null, to: null, error: 'listVersions 失败：' + String(error && error.message ? error.message : error) })
          continue
        }
        const target = pickUpdateTarget(list, bundle.version)
        if (target === null) {
          results.push({
            name: bundle.name, ok: true, from: bundle.version ?? null, to: null, application: 'up-to-date',
            note: list && list.status !== 'listed' ? (list.reason || '无法获取远端版本') : '已是最新版本',
          })
          continue
        }
        try {
          const result = await pm.updateBundle(bundle.name, target.version)
          results.push({
            name: bundle.name, ok: true, from: bundle.version ?? null, to: target.version,
            application: (result && result.application) || 'applied', result,
          })
        } catch (error) {
          results.push({
            name: bundle.name, ok: false, from: bundle.version ?? null, to: target.version,
            error: String(error && error.message ? error.message : error),
          })
        }
      }
      const updated = results.filter((entry) => entry.ok && entry.to !== null)
      const upToDate = results.filter((entry) => entry.ok && entry.to === null)
      const failed = results.filter((entry) => !entry.ok)
      return {
        results,
        result: {
          application: failed.length > 0
            ? 'failed'
            : updated.some((entry) => entry.application === 'restart-required') ? 'restart-required' : 'applied',
          updated: updated.length,
          upToDate: upToDate.length,
          failed: failed.length,
          truncated: pool.length > candidates.length,
          warnings: failed.map((entry) => entry.name + ': ' + entry.error),
        },
      }
    }
    case 'disable-conflicts': {
      const report = await buildReport(ctx, translateConfig(config))
      const only = body.id ? planConflictFix(report).filter((group) => group.id === String(body.id)) : null
      const groups = only ?? planConflictFix(report)
      const targets = []
      const seen = new Set()
      for (const group of groups) {
        for (const entry of group.disable) {
          const identity = entry.kind + ':' + entry.name
          if (seen.has(identity)) continue
          seen.add(identity)
          targets.push({
            kind: entry.kind, name: entry.name, entryId: entry.entryId,
            reason: '冲突组保留 ' + (group.keeper ? group.keeper.name : '?'),
          })
        }
      }
      if (body.dryRun === true) return { groups, targets, dryRun: true }
      return Object.assign({ groups, targets, dryRun: false }, await applyTargets(pm, targets))
    }
    case 'disable-erroring': {
      const report = await buildReport(ctx, translateConfig(config))
      const targets = planErrorFix(report)
      if (body.dryRun === true) return { targets, dryRun: true }
      return Object.assign({ targets, dryRun: false }, await applyTargets(pm, targets))
    }
    case 'translate': {
      const llm = llmService(ctx)
      if (llm === null) throw new Error('宿主未暴露 llm 服务（此 profile 未挂载 @deepseek-ai/dsh-llm）：无法翻译插件描述')
      const route = await resolveTranslationRoute(llm, config)
      // Both lists are in scope: installed third-party bundles AND the official
      // catalog entries that are not installed yet (the 官方目录 area).
      const bundles = await pm.listBundles()
      const requested = Array.isArray(body.names) ? body.names.map(String).filter((name) => name !== '') : []
      const refresh = body.refresh === true
      const cache = readTranslationCache()
      const pool = requested.length > 0
        ? bundles.filter((bundle) => requested.includes(bundle.name))
        : bundles.filter((bundle) => needsTranslation(bundle.description)
          && (refresh || cachedTranslation(cache, bundle.name, bundle.version) === null))
      const targets = pool.slice(0, 12)
      const translations = {}
      const skipped = []
      for (const bundle of targets) {
        const text = String(bundle.description ?? '').trim()
        if (!needsTranslation(text)) {
          skipped.push({ name: bundle.name, reason: '描述已是中文或为空' })
          continue
        }
        const key = bundle.name + '@' + (bundle.version ?? '')
        const cached = cachedTranslation(cache, bundle.name, bundle.version)
        if (cached !== null && !refresh) {
          translations[bundle.name] = cached
          continue
        }
        try {
          const translated = await translateText(llm, route, text.slice(0, 2000))
          if (translated === '') {
            skipped.push({ name: bundle.name, reason: '模型返回空译文' })
            continue
          }
          const entry = {
            text: translated,
            at: Date.now(),
            model: route.provider + '/' + route.model,
            installed: bundle.installed === true,
          }
          cache.entries[key] = entry
          translations[bundle.name] = entry
        } catch (error) {
          skipped.push({ name: bundle.name, reason: String(error && error.message ? error.message : error) })
        }
      }
      // The remaining count covers every description still lacking a
      // translation, so a second press continues where the first stopped
      // instead of re-reporting the same gap as if nothing had happened.
      const remaining = bundles.filter((bundle) => needsTranslation(bundle.description)
        && cachedTranslation(cache, bundle.name, bundle.version) === null).length
      return {
        route,
        translations,
        skipped,
        persisted: writeTranslationCache(cache),
        truncated: pool.length > targets.length,
        remaining,
      }
    }
    case 'translate-probe': {
      const llm = llmService(ctx)
      if (llm === null) return { available: false, reason: '宿主未暴露 llm 服务' }
      const providers = normalizeProviders(await Promise.resolve(llm.listProviders?.()))
      const models = {}
      for (const provider of providers.slice(0, 6)) {
        try {
          models[provider] = normalizeModels(await Promise.resolve(llm.listModels?.(provider)))
        } catch (error) {
          models[provider] = ['listModels 失败：' + String(error && error.message ? error.message : error)]
        }
      }
      let route = null
      let problem = null
      try {
        route = await resolveTranslationRoute(llm, config)
      } catch (error) {
        problem = String(error && error.message ? error.message : error)
      }
      let rawProviders = null
      try { rawProviders = JSON.parse(JSON.stringify(await Promise.resolve(llm.listProviders?.()))).slice(0, 2) } catch (error) { rawProviders = String(error) }
      return { available: true, providers, models, route, problem, rawProviders }
    }
    case 'capabilities': {
      const bundles = (await pm.listBundles()).filter((bundle) => bundle.installed)
      return {
        capabilities: bundles.map((bundle) => Object.assign(
          { name: bundle.name, version: bundle.version ?? null },
          scanCapabilities(bundle.name),
        )),
      }
    }
    default:
      throw new Error(`unknown action: ${String(action)}`)
  }
}

/** Resolve the applied config object into plain values for buildReport. */
function translateConfig(config) {
  return {
    enabled: readField(config, 'enabled'),
    autoRefreshSeconds: readField(config, 'autoRefreshSeconds'),
    showConsequenceHints: readField(config, 'showConsequenceHints'),
  }
}

/** Register the state and action routes; returns a disposer. */
function registerRoutes(ctx, config) {
  const disposers = [
    ctx.webServer.register({
      kind: 'exact',
      path: `${ROUTE}/state`,
      handler: (req, res) => {
        void (async () => {
          if (req.method !== 'GET') { sendJson(res, 405, { ok: false, error: 'GET only' }); return }
          const report = await buildReport(ctx, translateConfig(config))
          sendJson(res, 200, report)
        })().catch((error) => {
          ctx.logger?.error?.('plugin-triage: state failed', error)
          sendJson(res, 500, { ok: false, error: String(error && error.message ? error.message : error) })
        })
      },
    }),
    ctx.webServer.register({
      kind: 'exact',
      path: `${ROUTE}/action`,
      handler: (req, res) => {
        void (async () => {
          if (req.method !== 'POST') { sendJson(res, 405, { ok: false, error: 'POST only' }); return }
          if (!isLoopback(req)) {
            sendJson(res, 403, { ok: false, error: '治理动作仅允许本机（loopback）调用' })
            return
          }
          const body = await readBody(req)
          const action = String(body.action ?? '')
          if (!action) { sendJson(res, 400, { ok: false, error: 'missing action' }); return }
          const outcome = await runAction(ctx, config, action, body)
          sendJson(res, 200, { ok: true, action, ...outcome })
        })().catch((error) => {
          ctx.logger?.error?.('plugin-triage: action failed', error)
          const message = String(error && error.message ? error.message : error)
          sendJson(res, 400, { ok: false, error: message })
        })
      },
    }),
  ]
  return () => {
    for (const dispose of disposers) {
      try { if (typeof dispose === 'function') dispose() } catch { /* already gone */ }
    }
  }
}

function readField(config, key) {
  if (config === null || config === undefined) return undefined
  const value = config[key]
  if (value !== null && value !== undefined && typeof value.get === 'function') {
    try { return value.get() } catch { return value }
  }
  return value
}

/** Apply the Host half: routes only, everything else lives in the browser half. */
export function apply(ctx, config) {
  ctx.effect(() => registerRoutes(ctx, config ?? {}), 'plugin-triage: api routes')
}