/**
 * Compare two dotted numeric versions (`1.2.3-alpha.4`): -1/0/1, prerelease
 * sorts below its release. Never throws on malformed input; returns 0 then.
 */
function compareVersions(a, b) {
  const parse = (v) => {
    const match = /^v?(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?/.exec(String(v ?? ''))
    if (!match) return null
    return { major: +match[1], minor: +match[2], patch: +match[3], pre: match[4] ? match[4].split('.') : null }
  }
  const pa = parse(a)
  const pb = parse(b)
  if (pa === null || pb === null) return 0
  if (pa.major !== pb.major) return pa.major < pb.major ? -1 : 1
  if (pa.minor !== pb.minor) return pa.minor < pb.minor ? -1 : 1
  if (pa.patch !== pb.patch) return pa.patch < pb.patch ? -1 : 1
  if (pa.pre === null && pb.pre === null) return 0
  if (pa.pre === null) return 1
  if (pb.pre === null) return -1
  for (let i = 0; i < Math.max(pa.pre.length, pb.pre.length); i += 1) {
    const x = pa.pre[i]
    const y = pb.pre[i]
    if (x === undefined) return -1
    if (y === undefined) return 1
    const nx = /^\d+$/.test(x) ? +x : null
    const ny = /^\d+$/.test(y) ? +y : null
    if (nx !== null && ny !== null) { if (nx !== ny) return nx < ny ? -1 : 1; continue }
    if (nx !== null) return -1
    if (ny !== null) return 1
    if (x !== y) return x < y ? -1 : 1
  }
  return 0
}

/** Strip a leading operator, evaluating `x = <ver>` style comparators. */
function evalComparator(version, op, target) {
  const cmp = compareVersions(version, target)
  switch (op) {
    case '':
    case '=': return cmp === 0
    case '>': return cmp > 0
    case '>=': return cmp >= 0
    case '<': return cmp < 0
    case '<=': return cmp <= 0
    default: return true
  }
}

/** Expand a bare target into the concrete comparator set a partial target implies. */
function expandPartial(target) {
  const parts = String(target).split('.')
  while (parts.length < 3) parts.push('x')
  const [major, minor, patch] = parts
  const lo = `${major}.${minor === 'x' ? '0' : minor}.${patch === 'x' ? '0' : patch}`
  const list = [{ op: '>=', target: lo }]
  if (minor === 'x') list.push({ op: '<', target: `${+major + 1}.0.0` })
  else if (patch === 'x') list.push({ op: '<', target: `${major}.${+minor + 1}.0` })
  return list
}

/** Parse one comparator token (`>=1.2.3`, `^1.2`, `~1.2.3`, `1.2.x`, `*`). */
function parseComparator(token) {
  const raw = String(token).trim()
  if (raw === '' || raw === '*' || raw === 'x') return []
  let rest = raw
  let op = ''
  if (/^(>=|<=|>|<|=)/.test(rest)) { op = rest.slice(0, 2).match(/^(>=|<=)/) ? rest.slice(0, 2) : rest[0]; rest = rest.slice(op.length) }
  if (/^[0-9]/.test(rest) && /[xX*]/.test(rest.replace(/^v/, ''))) {
    // partial target may follow an explicit operator
    return expandPartial(rest).map((e) => ({ op: op || e.op, target: e.target }))
  }
  if (rest.startsWith('^')) {
    // caret: ^X.Y.Z  >=X.Y.Z <X+1.0.0 (X>0) | >=0.Y.Z <0.(Y+1).0 (X=0,Y>0) | >=0.0.Z <0.0.Z+1
    const parts = String(rest.slice(1)).split('.')
    while (parts.length < 3) parts.push('0')
    const major = +parts[0]
    const list = [{ op: '>=', target: `${parts[0]}.${parts[1]}.${parts[2]}` }]
    if (major > 0) list.push({ op: '<', target: `${major + 1}.0.0` })
    else if (+parts[1] > 0) list.push({ op: '<', target: `0.${+parts[1] + 1}.0` })
    else list.push({ op: '<', target: `0.0.${+parts[2] + 1}` })
    return list
  }
  if (rest.startsWith('~')) {
    // tilde: ~X.Y.Z >=X.Y.Z <X.(Y+1).0
    const parts = String(rest.slice(1)).split('.')
    while (parts.length < 3) parts.push('0')
    return [
      { op: '>=', target: `${parts[0]}.${parts[1]}.${parts[2]}` },
      { op: '<', target: `${parts[0]}.${+parts[1] + 1}.0` },
    ]
  }
  if (/[xX*]/.test(rest) || !/^[0-9]/.test(rest)) return expandPartial(rest)
  return [{ op, target: rest }]
}

/**
 * Tiny `semver.satisfies` subset: supports `||`, whitespace AND, `>= <= > < = ^ ~`
 * and `x` wildcards. Unknown shapes evaluate optimistically (the Host refuses
 * incompatible bundles anyway on install/update).
 */
export function satisfies(version, range) {
  if (!version || !range) return true
  const orGroups = String(range).split('||')
  return orGroups.some((group) => {
    const tokens = group.trim().split(/\s+/).filter(Boolean)
    if (tokens.length === 0) return true
    return tokens.every((token) => {
      const comparators = parseComparator(token)
      return comparators.every((c) => evalComparator(version, c.op, c.target))
    })
  })
}

