// dsh-plugin-triage — Host half.
//
// What this plugin does:
//   1. Collects the profile's live plugin inventory (runtime rows from
//      `pluginManager.listPlugins()`, bundle layers from `listBundles()`) and
//      classifies every conflict class DSH can actually hit:
//        - duplicate mounts: two bundles insert the same loader entry id;
//        - duplicate modules: two bundles load the same npm module;
//        - client mount overlap: two bundles inject the same client half modules;
//        - failed/pending fibers and bundle management errors;
//        - engine incompatibility: a bundle's declared `engines.dsh` range does
//          not accept the running DSH version, plus the exemption state.
//   2. Serves one same-origin report and one action endpoint, so the browser
//      half renders a 「冲突体检」 tab on the Plugins page with search, red
//      conflict groups with counts, consequence hints, and enable / disable /
//      remove / replace / update / exemption actions.
//
// All mutations go through the host `pluginManager` service, the same one the
// official Plugins page uses, so every change is persisted, applied live where
// HMR allows, and reported with its restart requirement.
//
// The settings namespace (`plugin-triage`) comes from the exported `Config`
// schema; the browser card for it is generated by the settings page itself.

